function guide(
  id: string,
  title: string,
  summary: string,
  category: GuideCategory,
  readTime: number,
  updatedAt: string,
  cover: string,
  isFeatured = false,
): Guide {
  const difficulty: GuideDifficulty = readTime >= 14 ? '高阶' : readTime >= 9 ? '进阶' : '入门';
  return {
    id,
    title,
    summary,
    category,
    readTime,
    updatedAt,
    cover,
    isFeatured,
    author: category === '角色养成' || category === '配队' ? '绳网研究所' : '新艾利都编辑部',
    difficulty,
    tags: [category, difficulty, '2.1 版本'],
    sections: [
      {
        id: 'overview',
        title: '核心结论',
        paragraphs: [
          summary,
          '本节先给出可直接执行的结论，再解释适用场景与替代方案，方便在有限时间内完成养成决策。',
        ],
      },
      {
        id: 'workflow',
        title: '实战流程',
        paragraphs: [
          '先在自由训练中确认关键阈值与操作节奏，再进入高压内容验证。每次只调整一个变量，便于判断实际收益。',
          '资源不足时优先保证稳定循环，避免为了理论上限牺牲生存、失衡窗口或队伍覆盖率。',
        ],
      },
      {
        id: 'checklist',
        title: '检查清单',
        paragraphs: [
          '确认角色等级、核心技、音擎与驱动盘主词条已经达到当前阶段的最低要求。',
          '记录一次完整战斗的轴长与资源缺口，并在版本更新后重新核对数据。',
        ],
      },
    ],
  };
}

